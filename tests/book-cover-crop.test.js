'use strict';
const assert = require('node:assert/strict');
const { normalizeCoverCrop } = require('../lib/cover-crop');
assert.deepEqual(normalizeCoverCrop({ enabled: true, x: 0, y: 100, zoom: 2.5 }), { enabled: true, x: 0, y: 100, zoom: 2.5 });
assert.deepEqual(normalizeCoverCrop({ enabled: true, x: 50, y: 50, zoom: 1 }), { enabled: true, x: 50, y: 50, zoom: 1 });
for (const v of [null, [], {}, { enabled: false, x: 10, y: 20, zoom: 1 }, { enabled: true, x: -1, y: 30, zoom: 1 }, { enabled: true, x: 30, y: 30, zoom: 3 }, { enabled: true, x: '20', y: 30, zoom: 1 }, { enabled: true, x: 30, y: 101, zoom: 1 }, { enabled: true, x: 30, y: 20, zoom: Infinity }]) assert.equal(normalizeCoverCrop(v), null);
const fs = require('node:fs');
const path = require('node:path');
const frontend = fs.readFileSync(path.join(__dirname, '../public/app.js'), 'utf8');
const layout = fs.readFileSync(path.join(__dirname, '../public/styles.css'), 'utf8');
const admin = fs.readFileSync(path.join(__dirname, '../public/staff.html'), 'utf8');
assert.match(frontend, /applyDisplayCoverCrop\(state\.coverImage, representative\.coverCrop\)/);
assert.match(frontend, /applyDisplayCoverCrop\(coverImage, book\.coverCrop\)/);
assert.match(frontend, /coverCrop: normalizedDisplayCoverCrop\(adminBookCrop\)/);
assert.match(frontend, /adminBookCrop = normalizedDisplayCoverCrop\(book\.coverCrop\)/);
assert.match(layout, /\.book-card__cover\s*\{[^}]*object-fit: contain;/);
assert.match(layout, /\.book-detail__cover\s*\{[^}]*object-fit: contain;/);
assert.match(admin, /id="admin-book-crop-enabled"/);
assert.match(admin, /id="admin-book-crop-zoom"/);
assert.match(admin, /id="admin-book-crop-x"/);
assert.match(admin, /id="admin-book-crop-y"/);
assert.match(admin, /id="admin-book-crop-reset"/);
console.log('Book cover crop validation passed');
