'use strict';
const assert=require('node:assert/strict');
const {startRun,pauseRun,cancelRun,resumeRun,chooseTask,finishTask,deferClaim,runStatus,applyRun,LEASE_MS}=require('../book-enrichment-collection');
const {recordCheck}=require('../book-enrichment-trial');
const isbn='9789086960088';
const book={id:'a',metadataIsbn:isbn,title:'Testtitel',author:'Test Auteur',description:'',tags:[]};
const copy={...book,id:'b',description:'Docenttekst',importProvenance:{fieldSources:{description:{sourceType:'manual'}}}};
const other={...book,id:'c',title:'Andere titel'};
const metadata={isbn,title:book.title,author:book.author,description:'Een beschrijving van een verhaal.',pageCount:128,coverUrl:'https://example.org/cover.jpg'};
let db={books:[book,copy,other,{...book,id:'personal',personalLoanOnly:true}],students:[{id:'p'}],history:[{id:'loan'}]};
let now=1000;
recordCheck(db,book,{status:'found',metadata},{source:'boekenbase',now:new Date(now)});
const run=startRun(db,['boekenbase','easycb'],{now,id:'first'});
assert.equal(run.ok,true);
assert.equal(startRun(db,['boekenbase']).ok,false);
assert.equal(runStatus(db).editions,2);
let claim=chooseTask(db,{now});
assert.equal(claim.book.id,'a');
assert.equal(claim.source,'easycb','Saved trial result skips a duplicate lookup');
assert.equal(chooseTask(db,{now}).wait,true);
assert.equal(deferClaim(db,claim),true);
claim=chooseTask(db,{now});
assert.equal(pauseRun(db,{now}).ok,true);
assert.equal(finishTask(db,claim,{status:'timeout',metadata:null},{now:++now}),true);
assert.equal(runStatus(db).state,'paused');
assert.equal(book.description,'');
db=JSON.parse(JSON.stringify(db));
assert.equal(resumeRun(db,{now}).ok,true);
claim=chooseTask(db,{now});
assert.equal(claim.source,'easycb');
assert.equal(finishTask(db,claim,{status:'found',metadata},{now:++now}),true);
claim=chooseTask(db,{now});
assert.equal(claim.book.id,'c');
const abandoned=claim;
assert.equal(chooseTask(db,{now:now+LEASE_MS+1}).source,'easycb');
claim=db.freeEnrichmentRun.inFlight;
assert.equal(finishTask(db,abandoned,{status:'found',metadata},{now:++now}),false);
assert.equal(finishTask(db,claim,{status:'not_found',metadata:null},{now:++now}),true);
assert.equal(chooseTask(db,{now}),null);
assert.equal(runStatus(db).state,'partial');
assert.equal(applyRun(db,run.id,{revision:'bad'}).ok,false);
assert.equal(resumeRun(db,{now}).ok,true);
claim=chooseTask(db,{now});
assert.equal(claim.source,'boekenbase');
finishTask(db,claim,{status:'not_found',metadata:null},{now:++now});
assert.equal(chooseTask(db,{now}),null);
const status=runStatus(db);
assert.equal(status.state,'ready');
assert.equal(status.completed,4);
assert.equal(db.books[0].description,'');
assert.equal(applyRun(db,run.id,{revision:'stale'}).ok,false);
const applied=applyRun(db,run.id,{revision:status.reviewRevision,now});
assert.equal(applied.ok,true);
assert.equal(applied.books,2);
assert.equal(db.books[0].pageCount,128);
assert.equal(db.books[1].description,'Docenttekst');
assert.equal(db.books[3].pageCount,undefined);
assert.equal(db.books[0].freeMetadataCheck.source,'EasyCB');
assert.deepEqual(db.students,[{id:'p'}]);
assert.deepEqual(db.history,[{id:'loan'}]);
assert.equal(startRun(db,['boekenbase'],{repeat:true,now,id:'second'}).ok,true);
const cancelledClaim=chooseTask(db,{now});
assert.equal(cancelRun(db,{now}).ok,true);
assert.equal(finishTask(db,cancelledClaim,{status:'not_found',metadata:null},{now}),false);
assert.equal(runStatus(db).state,'cancelled');
console.log('Durable free collection research, trial reuse, pause, crash recovery and confirmed application passed.');
