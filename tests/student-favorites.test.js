'use strict';
const assert=require('node:assert/strict');
const {workKey}=require('../book-reservations');
const {change,list}=require('../student-favorites');
const a={id:'a',title:'Spijt!',author:'Carry Slee.'},b={id:'b',title:'Spijt!',author:'Carry Slee',editionIsbn:'9789026995435'},hidden={id:'hidden',title:'Vermist',catalogHidden:true};
const db={students:[{id:'s1'},{id:'s2'},{id:'inactive',active:false}],books:[a,b,hidden]};
const key=workKey(a);
assert.equal(workKey(b),key);
assert.equal(change(db,'s1',{key,bookId:'a',favorite:true}).status,200);
assert.equal(change(db,'s1',{key,bookId:'b',favorite:true}).changed,false);
assert.equal(list(db,'s1').length,1);
assert.deepEqual(list(db,'s2'),[]);
assert.equal(change(db,'s2',{key,bookId:'a',favorite:false}).changed,false);
assert.equal(change(db,'s1',{key:workKey(hidden),bookId:'hidden',favorite:true}).status,404);
assert.equal(change(db,'inactive',{key,bookId:'a',favorite:true}).status,403);
assert.equal(change(db,'s1',{key:'forged',bookId:'a',favorite:true}).status,404);
db.books=[b];
assert.equal(list(db,'s1').length,1);
assert.equal(change(db,'s1',{key,favorite:false}).changed,true);
assert.deepEqual(list(db,'s1'),[]);
console.log('Private, title-level student favorites OK');
