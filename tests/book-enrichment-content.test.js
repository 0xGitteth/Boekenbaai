'use strict';
const assert=require('node:assert/strict');
const {recordCheck}=require('../book-enrichment-trial');
const {comparison,applyComparison}=require('../book-enrichment-comparison');
const {approvedDescriptions,descriptionCorpus}=require('../book-enrichment-content');
const {traitsForBook,profilesForWorks}=require('../student-choice-dialogue');
const {groupBooks}=require('../student-choice-recommendations');
const isbn='9789086960088';
const book={id:'one',metadataIsbn:isbn,title:'Testtitel',author:'Test Auteur',description:'Eigen omschrijving',
  importProvenance:{fieldSources:{description:{sourceType:'manual'}}},tags:[],status:'available'};
const db={books:[book]};
const text='Een meisje verzorgt paarden in de manege. Tijdens een wedstrijd moet ze haar paard helpen en leert ze meer over de verzorging van dieren.';
recordCheck(db,book,{status:'found',metadata:{isbn,title:book.title,author:book.author,description:text}},{source:'boekenbase'});
assert.equal(approvedDescriptions(book).length,0);
assert.equal(traitsForBook(book).has('animals'),false);
const preview=comparison(db,book);
assert.ok(!preview.changes.some(c=>c.field==='description'));
assert.ok(preview.changes.some(c=>c.field==='enrichmentDescriptions'));
assert.equal(applyComparison(db,book,preview.revision).ok,true);
assert.equal(book.description,'Eigen omschrijving');
assert.deepEqual(book.tags,[]);
assert.equal(book.enrichmentTags,undefined);
assert.equal(approvedDescriptions(book).length,1);
assert.ok(descriptionCorpus(book).includes(text));
assert.equal(traitsForBook(book).get('animals'),1,'Description evidence must stay weak');
const works=groupBooks(db);
assert.equal(works.length,1);
assert.ok(works[0].description.includes(text));
assert.equal(profilesForWorks(works).get(works[0].key).get('animals'),1);
assert.equal(approvedDescriptions({...book,title:'Ander boek'}).length,0);
assert.equal(approvedDescriptions({...book,themesCleared:true}).length,0);
assert.equal(traitsForBook({...book,themesCleared:true}).has('animals'),false);
assert.equal(comparison(db,book).changes.length,0,'Approved evidence must not be re-added');
const restored=JSON.parse(JSON.stringify(book));
assert.equal(approvedDescriptions(restored).length,1);
console.log('Approved source descriptions preserve teacher text and contribute weak evidence to both recommendation paths.');
